-- Per-user Agent configuration. knowledge_base_ids / allowed_tools are JSON arrays,
-- but runtime still re-validates them against current KB permissions and the tool registry.
CREATE TABLE agent_profile (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id            bigint NOT NULL,
    name               varchar(100) NOT NULL,
    system_prompt      text,
    kb_selection_mode  varchar(16) NOT NULL,
    knowledge_base_ids text NOT NULL DEFAULT '[]',
    allowed_tools      text NOT NULL DEFAULT '[]',
    create_time        timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time        timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_agent_profile_kb_selection_mode
        CHECK (kb_selection_mode IN ('all', 'selected', 'none'))
);

CREATE INDEX idx_agent_profile_user_id ON agent_profile (user_id);
