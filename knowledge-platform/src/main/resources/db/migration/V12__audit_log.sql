-- 操作审计（append-only）。
--
-- 设计取舍（对齐 WeKnora 的 audit_logs，但按本项目规模裁剪）：
--   · 只增不改：没有 update_time、没有软删除列。删除只发生在保留策略清扫（AuditLogRetention）。
--   · 不自建查询 API：本项目是单实例本地部署，追溯靠一条 SQL 足够（见文件末尾示例）。
--   · outcome 用 CHECK 钉住取值，避免代码里写错拼写而静默落库。
--   · details 用 jsonb：动作特有负载（文档名、知识库 ID、密钥前缀等），不预先定列。
--   · 不存 actor 用户名快照：只存 id，用户改名后回溯语义仍是"当时那个账号"（id 不变）。
CREATE TABLE audit_log (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_user_id  bigint,
    action         varchar(64) NOT NULL,
    target_type    varchar(32),
    target_id      varchar(64),
    outcome        varchar(16) NOT NULL DEFAULT 'success',
    details        jsonb,
    request_id     varchar(128),
    created_at     timestamp   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_audit_log_outcome
        CHECK (outcome IN ('success', 'accepted', 'denied', 'failed', 'partial', 'canceled'))
);

-- 保留策略清扫按 created_at 范围删，走这条索引。
CREATE INDEX idx_audit_log_created_at ON audit_log (created_at DESC);

-- 「最近谁删了东西」按 action 过滤 + 时间倒序，走这条。
CREATE INDEX idx_audit_log_action_created_at ON audit_log (action, created_at DESC);

-- 「某个知识库/文档被谁动过」按目标追溯。
CREATE INDEX idx_audit_log_target ON audit_log (target_type, target_id);

