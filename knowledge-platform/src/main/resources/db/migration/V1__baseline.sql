-- EKIP schema 唯一权威（原 docker/init/mysql/01-schema.sql + docker/init/pg/01-schema.sql 合并）。
-- 单 PostgreSQL 承载业务表与 document_chunk；Milvus 为可选向量副本，不在此建。

CREATE EXTENSION IF NOT EXISTS vector WITH SCHEMA public;

-- ---------- 业务表 ----------
-- 注意：表名叫 sys_user 而不是 user —— user 是 PostgreSQL 保留字，
-- CREATE TABLE user 直接语法错误，带引号的 "user" 会污染所有 SQL 与 MyBatis 映射。

CREATE TABLE sys_user (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username    varchar(50)  NOT NULL,
    password    varchar(255) NOT NULL,          -- BCrypt 密文
    email       varchar(100),
    department  varchar(100),
    status      int NOT NULL DEFAULT 1,         -- 1 正常 / 0 禁用
    create_time timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    -- 原 MySQL 的 ON UPDATE CURRENT_TIMESTAMP 在 PG 无对应语法，
    -- 改由 AuditMetaObjectHandler 在应用层填充（见 config/AuditMetaObjectHandler.java）
    update_time timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 用户名唯一性：**大小写不敏感**，对齐改造前 MySQL `utf8mb4_0900_ai_ci` 的语义。
-- PG 的 varchar 比较是大小写敏感的，故用表达式唯一索引 lower(username)，而不是
-- `UNIQUE (username)` —— 后者会让 Admin 与 admin 成为两个账号（企业登录场景的仿冒面）。
-- 查询侧配套：UserMapper.selectByUsername 写 `lower(username) = lower(#{username})`，
-- 与索引表达式一致（同一个 lower(username)，planner 才用得上这个索引）。
-- ⚠️ 改这里必须同步改 V1 已应用过的库：Flyway 会校验已应用迁移的 checksum，
--    直接改文件会让下一次启动报 checksum mismatch（见设计 §10.4 / fix-wave 记录）。
CREATE UNIQUE INDEX uk_sys_user_username ON sys_user (lower(username));

CREATE TABLE knowledge_base (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        varchar(100) NOT NULL,
    description varchar(500),
    creator_id  bigint NOT NULL,
    create_time timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE document (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    knowledge_base_id bigint NOT NULL,
    file_name         varchar(255) NOT NULL,
    file_type         varchar(50),
    file_path         varchar(500),
    file_size         bigint,
    uploader_id       bigint,
    status            int DEFAULT 0,
    create_time       timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE document_task (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id   bigint NOT NULL,
    status        int NOT NULL DEFAULT 0,
    retry_count   int NOT NULL DEFAULT 0,
    error_message varchar(1000),
    create_time   timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time   timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    start_time    timestamp,
    finish_time   timestamp
);

CREATE TABLE knowledge_base_member (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    knowledge_base_id bigint NOT NULL,
    user_id           bigint NOT NULL,
    create_time       timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_kb_user UNIQUE (knowledge_base_id, user_id)
);

CREATE TABLE mcp_api_key (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        bigint NOT NULL,
    key_hash       char(64)    NOT NULL,        -- SHA-256 小写十六进制；明文永不入库
    key_prefix     char(12)    NOT NULL,        -- ekip_mcp_ + 3 位随机体，仅供辨认
    name           varchar(100) NOT NULL,
    status         int NOT NULL DEFAULT 0,      -- 0=ACTIVE 1=REVOKED
    expires_at     timestamp,
    last_used_time timestamp,
    create_time    timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time    timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_key_hash UNIQUE (key_hash)
);
CREATE INDEX idx_mcp_api_key_user_id ON mcp_api_key (user_id);

-- ---------- chunk 主数据 + 向量 ----------
-- embedding 用 halfvec 而非 vector：pgvector 的 HNSW 维度上限按类型分
--   vector=2000 / halfvec=4000 / bit=64000
-- 2560 维超出 vector 上限（故改造前 PG 侧根本建不了向量索引，只能全表扫描），
-- 而 halfvec 的 4000 装得下。根因是索引页不能跨 PG 的 8KB page，float16 占一半空间故上限翻倍。
-- 代价：float32 → float16 有舍入误差，余弦排序基本不受影响。
CREATE TABLE document_chunk (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id       bigint NOT NULL,
    knowledge_base_id bigint,
    chunk_index       integer NOT NULL,
    content           text NOT NULL,
    char_count        integer,
    embedding         halfvec(2560),
    search_vector     tsvector,                 -- jieba 预分词文本，PG 'simple' 词典不切中文
    source_type       varchar(32),
    page_no           integer,
    heading_path      text,
    table_id          varchar(64),
    row_index         integer,
    create_time       timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time       timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_chunk_search_vector        ON document_chunk USING gin   (search_vector);
CREATE INDEX idx_document_chunk_document_id ON document_chunk USING btree (document_id);
CREATE INDEX idx_document_chunk_kb          ON document_chunk USING btree (knowledge_base_id);
CREATE INDEX idx_document_chunk_embedding_hnsw
    ON document_chunk USING hnsw (embedding halfvec_cosine_ops);
