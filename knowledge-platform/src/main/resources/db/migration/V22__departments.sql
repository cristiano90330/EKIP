CREATE TABLE department (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE
);

UPDATE sys_user SET department = NULLIF(btrim(department), '') WHERE department IS NOT NULL;

INSERT INTO department (name)
SELECT DISTINCT department FROM sys_user WHERE department IS NOT NULL;

CREATE INDEX idx_sys_user_department ON sys_user (department);
ALTER TABLE sys_user ADD CONSTRAINT fk_sys_user_department
    FOREIGN KEY (department) REFERENCES department(name) ON UPDATE CASCADE ON DELETE SET NULL;
