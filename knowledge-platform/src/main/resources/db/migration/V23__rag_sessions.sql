CREATE TABLE rag_session (
    id UUID PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES sys_user(id) ON DELETE CASCADE,
    knowledge_base_id BIGINT REFERENCES knowledge_base(id) ON DELETE CASCADE,
    scope_key TEXT NOT NULL,
    title VARCHAR(100) NOT NULL DEFAULT '新会话',
    active_turn UUID,
    active_until TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_rag_session_owner ON rag_session (user_id, updated_at DESC, id);
CREATE INDEX idx_rag_session_knowledge_base ON rag_session (knowledge_base_id);

CREATE TABLE rag_session_turn (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id UUID NOT NULL REFERENCES rag_session(id) ON DELETE CASCADE,
    question TEXT NOT NULL,
    response JSONB NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_rag_session_turn_history ON rag_session_turn (session_id, id DESC);
