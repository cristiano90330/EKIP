CREATE TABLE document_upload_receipt (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id           bigint NOT NULL,
    knowledge_base_id bigint NOT NULL,
    request_key       varchar(128) NOT NULL,
    content_sha256    char(64) NOT NULL,
    document_id       bigint REFERENCES document(id) ON DELETE CASCADE,
    task_id           bigint REFERENCES document_task(id) ON DELETE CASCADE,
    create_time       timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_upload_receipt_user_kb_key
        UNIQUE (user_id, knowledge_base_id, request_key),
    CONSTRAINT ck_upload_receipt_request_key_nonblank
        CHECK (length(trim(request_key)) > 0)
);

CREATE INDEX idx_upload_receipt_document ON document_upload_receipt(document_id);
